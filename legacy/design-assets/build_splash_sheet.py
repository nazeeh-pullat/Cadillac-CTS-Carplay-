#!/usr/bin/env python3
"""Turn the owner-supplied splash GIF into a cropped sprite sheet plus frame timings.

Near-black pixels are clamped to pure black so the splash background can be exactly #000000
without a faint rectangle around the animation. Run from the repository root:
    python legacy/design-assets/build_splash_sheet.py legacy/design-assets/splash-source.gif
"""
import sys
from pathlib import Path
from PIL import Image, ImageFilter

BLACK_POINT = 18      # channel values at or below this become 0
COLUMNS = 7
SCALE = 3             # pre-scale with Lanczos so the splash is sharper than a runtime bilinear stretch
PAD = 4

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'design-assets' / 'splash-source.gif'
gif = Image.open(source)
levels = [0 if v <= BLACK_POINT else round((v - BLACK_POINT) * 255 / (255 - BLACK_POINT)) for v in range(256)]

# The artwork is flat white-on-black line art, so after upscaling a gentle S-curve snaps blurry edges
# to crisp, still anti-aliased ones (a light-weight stand-in for vectorising every frame).
import math
edge = [0 if v <= BLACK_POINT else min(255, max(0, round(255 / (1 + math.exp(-(v - 128) / 26.0)) * 1.04 - 3))) for v in range(256)]
frames, durations = [], []
for index in range(gif.n_frames):
    gif.seek(index)
    frame = gif.convert('RGB').point(levels * 3)
    frames.append(frame)
    durations.append(gif.info.get('duration', 60) or 60)

width, height = frames[0].size
union = None
for frame in frames:
    box = frame.convert('L').point(lambda v: 255 if v > 0 else 0).getbbox()
    if box:
        union = box if union is None else (min(union[0], box[0]), min(union[1], box[1]), max(union[2], box[2]), max(union[3], box[3]))
left, top = max(0, union[0] - PAD), max(0, union[1] - PAD)
right, bottom = min(width, union[2] + PAD), min(height, union[3] + PAD)
crop_w, crop_h = right - left, bottom - top

rows = -(-len(frames) // COLUMNS)
cell_w, cell_h = crop_w * SCALE, crop_h * SCALE
sheet = Image.new('RGB', (cell_w * COLUMNS, cell_h * rows), (0, 0, 0))
for index, frame in enumerate(frames):
    big = frame.crop((left, top, right, bottom)).resize((cell_w, cell_h), Image.LANCZOS)
    big = big.filter(ImageFilter.UnsharpMask(radius=2.0, percent=110, threshold=1)).point(edge * 3)
    sheet.paste(big, ((index % COLUMNS) * cell_w, (index // COLUMNS) * cell_h))

drawable = root / 'src' / 'main' / 'res' / 'drawable-nodpi'
drawable.mkdir(parents=True, exist_ok=True)
sheet.save(drawable / 'splash_sheet.png', optimize=True)

offset_x = (left + right) / 2 - width / 2
offset_y = (top + bottom) / 2 - height / 2
kotlin = root / 'src' / 'main' / 'java' / 'com' / 'shihab' / 'diplay' / 'legacy' / 'SplashFrames.kt'
kotlin.write_text(f'''package com.shihab.diplay.legacy

/** Generated by design-assets/build_splash_sheet.py from the owner's splash GIF; do not edit. */
internal object SplashFrames {{
    const val COLUMNS = {COLUMNS}
    const val FRAME_WIDTH = {cell_w}
    const val FRAME_HEIGHT = {cell_h}
    /** Crop centre relative to the source frame centre, in source pixels. */
    const val OFFSET_X = {offset_x * SCALE:.1f}f
    const val OFFSET_Y = {offset_y * SCALE:.1f}f
    /** Width of the final crest in source pixels, used to size the animation on screen. */
    const val CREST_WIDTH = {(union[2] - union[0]) * SCALE}f
    val DURATIONS_MS = intArrayOf({', '.join(str(d) for d in durations)})
    val TOTAL_MS = DURATIONS_MS.sum()
}}
''', encoding='utf-8')
print(f'frames={len(frames)} crop={cell_w}x{cell_h} sheet={sheet.size} total={sum(durations)}ms')
